  constructor() {
    const savedLanguage = localStorage.getItem('language') as Language | null;
    if (savedLanguage && this.isValidLanguage(savedLanguage)) {
      this.currentLanguage.set(savedLanguage);
      this.applyLanguageDirection(savedLanguage);
    }
  }

  private isValidLanguage(lang: any): lang is Language {
    return ['tr', 'en', 'ar'].includes(lang);
  }

  private applyLanguageDirection(lang: Language) {
    if (lang === 'ar') {
      document.documentElement.dir = 'rtl';
      document.documentElement.lang = 'ar';
    } else {
      document.documentElement.dir = 'ltr';
      document.documentElement.lang = lang;
    }
  }

  setLanguage(lang: Language) {
    this.currentLanguage.set(lang);
    localStorage.setItem('language', lang);
    this.applyLanguageDirection(lang);
  }

  getLanguage(): Language {
    return this.currentLanguage();
  }

  getLanguageSignal() {
    return this.currentLanguage;
  }

  translate(key: string, lang?: Language): string {
    const targetLang = lang || this.currentLanguage();
    const translations = this.translations[targetLang] as Record<string, string>;
    return translations[key] || key;
  }

  getTranslations(lang?: Language) {
    const targetLang = lang || this.currentLanguage();
    return this.translations[targetLang];
  }
